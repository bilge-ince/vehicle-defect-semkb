-- ===========================================================================
-- odi.inv — DEFECT INVESTIGATIONS
-- Source: FLAT_INV.txt, dictionary https://static.nhtsa.gov/odi/ffdd/inv/INV.txt
-- 11 fields, TAB delimited, no header row.
-- VERIFIED 2026-08-07 against INV.txt (Last Updated September 5, 2023) and by
-- counting fields on all 154,249 lines.
--
-- NAMING NOTE: the dictionary calls field 1 "NHTSA ACTION NUMBER" — with spaces,
-- not an identifier. NHTSA publishes no canonical SQL column name for it. We use
-- nhtsa_action_number. This is OUR choice, the only one in this file; every other
-- column name is the publisher's verbatim. Flagged so nobody mistakes it for
-- source truth.
-- ===========================================================================
DROP TABLE IF EXISTS odi.inv CASCADE;

CREATE TABLE odi.inv (
    nhtsa_action_number TEXT,   --  1  see NAMING NOTE above
    make                TEXT,   --  2
    model               TEXT,   --  3
    year                TEXT,   --  4
    compname            TEXT,   --  5
    mfr_name            TEXT,   --  6
    odate               TEXT,   --  7
    cdate               TEXT,   --  8
    campno              TEXT,   --  9  joins to odi.rcl.campno
    subject             TEXT,   -- 10
    summary             TEXT    -- 11
);


-- ===========================================================================
-- Indexes
--
-- Sized for a live demo on a laptop: every scripted question must return in
-- well under a second, because dead air while an audience watches a spinner is
-- the fastest way to lose a room.
--
-- Built AFTER this script only in the sense that the loader runs next; Postgres
-- will populate them during COPY. If you are loading the full 2.2 M-row
-- complaints file and the load feels slow, drop the indexes, load, recreate.
-- For --subset 250000 the difference is not worth the extra step.
-- ===========================================================================

-- Complaints: the four columns every scripted question filters or groups on.
CREATE INDEX IF NOT EXISTS cmpl_maketxt_idx   ON odi.cmpl (maketxt);
CREATE INDEX IF NOT EXISTS cmpl_yeartxt_idx   ON odi.cmpl (yeartxt);
CREATE INDEX IF NOT EXISTS cmpl_compdesc_idx  ON odi.cmpl (compdesc);
CREATE INDEX IF NOT EXISTS cmpl_datea_idx     ON odi.cmpl USING btree (datea);

-- The two *other* date columns get an index too. The demo's central "which date
-- column did the model pick?" beat compares plans/results across all three, and
-- an unindexed faildate would make the wrong answer look slow rather than wrong.
CREATE INDEX IF NOT EXISTS cmpl_faildate_idx  ON odi.cmpl USING btree (faildate);
CREATE INDEX IF NOT EXISTS cmpl_ldate_idx     ON odi.cmpl USING btree (ldate);

-- Act 4 (hybrid search): full-text over the complaint narrative, combined with a
-- structured predicate on maketxt/yeartxt. Expression index with an explicit
-- regconfig — 'english' as a literal is IMMUTABLE, a bare to_tsvector(cdescr)
-- is not and would be rejected here.
-- coalesce() because cdescr is empty string / NULL on a small number of rows.
CREATE INDEX IF NOT EXISTS cmpl_cdescr_fts_idx
    ON odi.cmpl
    USING gin (to_tsvector('english', coalesce(cdescr, '')));

-- Recalls and investigations: enough to make joins and lookups instant.
CREATE INDEX IF NOT EXISTS rcl_maketxt_idx    ON odi.rcl (maketxt);
CREATE INDEX IF NOT EXISTS rcl_yeartxt_idx    ON odi.rcl (yeartxt);
CREATE INDEX IF NOT EXISTS rcl_compname_idx   ON odi.rcl (compname);
CREATE INDEX IF NOT EXISTS rcl_datea_idx      ON odi.rcl USING btree (datea);
CREATE INDEX IF NOT EXISTS rcl_campno_idx     ON odi.rcl (campno);

CREATE INDEX IF NOT EXISTS inv_make_idx       ON odi.inv (make);
CREATE INDEX IF NOT EXISTS inv_compname_idx   ON odi.inv (compname);
CREATE INDEX IF NOT EXISTS inv_campno_idx     ON odi.inv (campno);
CREATE INDEX IF NOT EXISTS inv_odate_idx      ON odi.inv USING btree (odate);


