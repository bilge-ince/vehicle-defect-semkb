-- ---------------------------------------------------------------------------
-- 01_schema.sql — physical landing schema for the NHTSA ODI flat files.
--
-- WHERE THIS FITS IN THE DEMO
-- ---------------------------
-- This file is the *antagonist* of the demo. It deliberately reproduces the
-- publisher's physical column names exactly as they appear in the flat file,
-- lowercased and nothing else:
--
--     cmplid  odino  compdesc  cmpl_type  ldate  datea  faildate
--     orig_equip_yn  loc_of_tire  occurences  prod_type  mfr_name
--
-- Three different date columns. A misspelled column (`occurences`, one 'r').
-- A misspelled column in recalls (`conequence_defect`, missing the 's').
-- No foreign keys, no friendly aliases, no documentation in the object names.
-- This is what an SAP-derived enterprise warehouse actually looks like, and it
-- is why an unaided frontier model gets Text-to-SQL wrong here.
--
-- DO NOT "clean this up". The cryptic names are the demo.
--
-- Everything is TEXT. That is deliberate, not laziness:
--   * The source is dirty (empty strings, literal spaces, 9999 for unknown year,
--     zero-filled numerics, dates that are not dates).
--   * A cast failure mid-COPY on stage is unrecoverable. Landing as TEXT means
--     the load cannot fail on data quality.
--   * The typed/derived layer is shown as a COMMENTED-OUT pattern at the bottom.
--     We do not create it, because a friendly typed view would hand the model the
--     answer and destroy the point of the demo.
--
-- RUN ORDER
-- ---------
--   1. sql/01_schema.sql          <-- you are here (run BEFORE loading)
--   2. data/load_nhtsa.py         COPY the flat files in
--   3. sql/02_comments.sql        GENERATED by scripts/generate_comments.py
--   4. sql/03_semantic_kb.sql     ...
--
-- Idempotent: safe to re-run. Re-running DROPs and recreates the tables, so it
-- also wipes the data — re-run the loader afterwards.
--
-- FIELD LISTS VERIFIED 2026-08-07 against BOTH the published data dictionaries
-- and the actual flat files (every single line counted, not a sample):
--
--   odi.cmpl  51 columns   2,232,666 rows   all lines exactly 51 fields
--   odi.rcl   29 columns     325,734 rows   all non-blank lines exactly 29 fields
--                                           (5 blank lines in the PRE_2010 part
--                                            are skipped by the loader)
--   odi.inv   11 columns     154,249 rows   all lines exactly 11 fields
--
-- !! The widely-circulated "complaints has 49 fields" figure is STALE. !!
-- NHTSA added field 50 (STATE_OF_INCIDENT) and field 51 (VEHICLE_OPERATOR) on
-- 30 April 2026. Likewise recalls is 29 fields, not 27: fields 28 (DO_NOT_DRIVE)
-- and 29 (PARK_OUTSIDE) were added in May 2025. If you are reading this long
-- after August 2026, re-check the dictionaries before the demo — load_nhtsa.py
-- will abort loudly if the file has drifted again.
-- ---------------------------------------------------------------------------

\set ON_ERROR_STOP on

CREATE SCHEMA IF NOT EXISTS odi;

COMMENT ON SCHEMA odi IS
  'NHTSA Office of Defects Investigation flat files, landed verbatim. '
  'Public domain. Physical column names are the publisher''s, unmodified.';


