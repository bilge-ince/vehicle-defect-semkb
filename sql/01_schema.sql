-- ===========================================================================
-- Verification
--
-- On a FIRST run (before the loader) every count is 0 and the date range is
-- NULL. That is expected — this script creates the tables, load_nhtsa.py fills
-- them. Re-run this SELECT after loading, or just read the loader's own summary.
--
-- The date range matters more than the row count. A previous version of this
-- demo asked the agent about a year that had no rows and returned an empty
-- result on stage. Always know your date range before you present.
-- ===========================================================================
SELECT
    'odi.cmpl' AS table_name,
    count(*)                                       AS row_count,
    min(NULLIF(datea, ''))                         AS min_datea,
    max(NULLIF(datea, ''))                         AS max_datea
FROM odi.cmpl
UNION ALL
SELECT
    'odi.rcl',
    count(*),
    min(NULLIF(datea, '')),
    max(NULLIF(datea, ''))
FROM odi.rcl
UNION ALL
SELECT
    'odi.inv',
    count(*),
    min(NULLIF(odate, '')),   -- inv has no datea; odate = date opened
    max(NULLIF(odate, ''))
FROM odi.inv;

